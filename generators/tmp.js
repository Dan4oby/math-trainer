(function () {
  'use strict';

  var L = window.GeneratorLib;

  /* ─────────── утилита: одиночный вопрос ─────────── */

  function q(text, options, correct, key) {
    return { text: text, options: options, correct: correct, key: key };
  }

  /* ─────────── общая функция для двух слайдов с прямой ─────────── */

  function drawSumLine(opts) {
    return Svg.canvas({
      width: 500, height: 160, unit: 40,
      originY: 100,
      children: [
        Svg.numberLine({ from: -4, to: 5, arrow: 'right', labelSize: 14 }),
        Svg.point(opts.a, 0, { color: '#2563eb', label: opts.labelA, labelSide: 'top' }),
        Svg.point(opts.b, 0, { color: '#16a34a', label: opts.labelB, labelSide: 'top' }),
        Svg.vector(opts.a, 0, opts.b, 0, {
          color: '#ef4444', label: opts.arrow, labelDy: -28
        })
      ]
    });
  }

  /* ─────────── фабрики фаз ─────────── */

  function questionPhase(key, title, generator) {
    return {
      key:      key,
      label:    'Вопрос',
      title:    title,
      total:    1,
      progress: 'group',
      top:      [{ type: 'example-string', class: 'question' }],
      bottom:   L.singleChoicePanel,
      generate: generator,
      check:    L.checkSingleChoice,
      formatAnswer: L.formatSingleChoice
    };
  }

  function infoPhase(key, label, slides) {
    return {
      key:      key,
      kind:     'info',
      label:    label,
      title:    label,
      total:    slides.length,
      progress: 'group',
      top:      [{ type: 'info-slide' }],
      generate: L.slides(slides)
    };
  }

  function visualInfoPhase(key, label, slides) {
    var p = infoPhase(key, label, slides);
    p.top = [{ type: 'info-slide' }, { type: 'svg' }];
    return p;
  }

  /* ─────────── регистрация ─────────── */

  L.register('mathOperations', {
    id:   'mathOperations',
    name: 'Математические операции',

    rules: [
      '📖 Урок из нескольких шагов',
      '✍️ После каждого верного ответа — пояснение',
      '🎯 Ошибочный ответ вернётся к тебе позже'
    ],

    phases: [

      /* 1 */
      questionPhase('q1', 'Что такое математическая операция',
        function () {
          return q(
            'Что такое математическая операция?',
            [
              'Преобразование одного или нескольких чисел в новое число по заданным правилам',
              'Замена одного числа другим без правил',
              'Запись чисел в порядке возрастания',
              'Сравнение двух чисел'
            ],
            0,
            'q1'
          );
        }
      ),

      /* 2 */
      infoPhase('m2', 'Правильно!', [
        {
          title: 'Вспомним',
          text:
            'Мы уже проходили это в самом начале. Когда представляли ' +
            'математические операции в виде фабрик, которым мы через запятую ' +
            'даём два числа, а они в ответ возвращают результат:<br>' +
            '$+)\\ 2, 3 \\to 5$<br>' +
            '$−)\\ 2, 3 \\to -1$<br>' +
            '$*)\\ 2, 3 \\to 6$'
        }
      ]),

      /* 3 */
      questionPhase('q3', 'Зачем нужны скобки',
        function () {
          return q(
            'Если существуют числа и математические операции над числами, ' +
            'то для чего нужны скобки?',
            [
              'Для задания первоочередного приоритета вычисления',
              'Для замены знаков операций',
              'Для оформления ответа',
              'Для разделения чисел'
            ],
            0,
            'q3'
          );
        }
      ),

      /* 4 */
      infoPhase('m4', 'Правильно!', [
        {
          title: 'Зачем нужны скобки',
          text:
            'Скобки нужны для того, чтобы <b>изменить стандартный порядок ' +
            'действий</b> и чётко указать, какие вычисления нужно произвести ' +
            'в первую очередь.<br>' +
            '$2 \\cdot 3 - 2 \\cdot (3 - 2)$'
        }
      ]),

      /* 5 */
      questionPhase('q5', 'Слагаемые',
        function () {
          return q(
            'Что такое слагаемые?',
            [
              'Числа, которые участвуют в операции сложения',
              'Числа, которые перемножаются',
              'Результат вычитания',
              'Части выражения с буквами'
            ],
            0,
            'q5'
          );
        }
      ),

      /* 6 */
      questionPhase('q6', 'Свойство сложения',
        function () {
          return q(
            'Какое свойство есть у операции сложения?',
            [
              'Порядок вычисления слагаемых никак не влияет на результат',
              'Порядок вычисления слагаемых влияет на результат',
              'Слагаемые можно только перемножать',
              'Результат всегда равен нулю'
            ],
            0,
            'q6'
          );
        }
      ),

      /* 7 */
      infoPhase('m7', 'Правильно!', [
        {
          title: 'Главное свойство сложения',
          text:
            'Это главное свойство. Из него уже выходят свойства: ' +
            'от перемены слагаемых сумма не меняется и ' +
            '$(4 + 1) + 2 = 4 + (1 + 2)$'
        }
      ]),

      /* 8 */
      questionPhase('q8', 'Вычитание через сложение',
        function () {
          return q(
            'Как определяется операция вычитания через операцию сложения?',
            [
              '3 − 2 = 3 + (−2)',
              '3 − 2 = 3 − (−2)',
              '3 − 2 = −3 + 2',
              '3 − 2 = −3 − 2'
            ],
            0,
            'q8'
          );
        }
      ),

      /* 9 — визуальное пояснение (2 слайда) */
      visualInfoPhase('m8', 'Правильно!', [
        {
          title: 'Давай покажем это визуально',
          text:
            'Мы наверняка легко поймём, что такое прибавить $3$ к $−2$.<br>' +
            'Это то же самое, что сдвинуться вправо на три единицы.<br>' +
            'Получаем: $(-2) + 3 = 1$',
          svg: drawSumLine({
            a: -2, b: 1, labelA: '−2', labelB: '1', arrow: '+3'
          })
        },
        {
          title: 'И обратный ход',
          text:
            'Значит, поймём и обратное: прибавить $−2$ к $3$ — сдвинуться ' +
            'влево на две единицы.<br>' +
            'Получаем: $3 + (-2) = 1$. Значит, $3 - 2 = 3 + (-2)$',
          svg: drawSumLine({
            a: 3, b: 1, labelA: '3', labelB: '1', arrow: '+(−2)'
          })
        }
      ]),

      /* 9 */
      questionPhase('q9', 'Свойство в переменных',
        function () {
          return q(
            'Как мы можем записать сформулированное свойство в переменных?',
            [
              'a − b = a + (−b)',
              'a − b = a − b',
              'a − b = −a + b',
              'a − b = −a − b'
            ],
            0,
            'q9'
          );
        }
      ),

      /* 10 */
      questionPhase('q10', 'Недействительное свойство',
        function () {
          return q(
            'Какое свойство для вычитания недействительно?',
            [
              'Порядок вычитания не имеет значения',
              'Вычитание можно заменить сложением с противоположным числом',
              'Вычитание не коммутативно',
              'Вычитание можно представить как сложение'
            ],
            0,
            'q10'
          );
        }
      ),

      /* 11 */
      questionPhase('q11', 'Умножение',
        function () {
          return q(
            'Что такое умножение?',
            [
              'Операция, при которой число складывается с собой столько раз, ' +
              'на сколько число умножается',
              'Операция деления на равные части',
              'Операция сложения двух чисел',
              'Операция, при которой число увеличивается на единицу'
            ],
            0,
            'q11'
          );
        }
      ),

      /* 12 */
      infoPhase('m12', 'Правильно!', [
        {
          title: 'Умножение как сложение',
          text:
            'Рассмотрим примеры:<br>' +
            '$10 \\cdot 1$ — по сути то же самое, что $10$<br>' +
            '$10 \\cdot 3$ — по сути то же самое, что ' +
            '$\\underbrace{10 + 10 + 10}_{3\\ раза}$<br>' +
            '$3 \\cdot 10$ — по сути то же самое, что ' +
            '$\\underbrace{3 + 3 + \\ldots + 3}_{10\\ раз}$<br><br>' +
            'То есть мы всегда можем представить умножение в виде сложения ' +
            'этим способом.'
        }
      ])

    ]
  });

})();